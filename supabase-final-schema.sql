-- assignments: teacher manages, students see own/class/global
create policy assignments_select on public.assignments for select to authenticated using (
  public.is_teacher()
  or target_user_id=auth.uid()
  or (target_user_id is null and (target_class is null or target_class=(select class_name from public.profiles where id=auth.uid())))
);
create policy assignments_teacher_insert on public.assignments for insert to authenticated with check(public.is_teacher() and created_by=auth.uid());
create policy assignments_teacher_update on public.assignments for update to authenticated using(public.is_teacher()) with check(public.is_teacher());
create policy assignments_teacher_delete on public.assignments for delete to authenticated using(public.is_teacher());

create policy mistakes_select on public.mistakes for select to authenticated using(user_id=auth.uid() or public.is_teacher());
create policy mistakes_insert on public.mistakes for insert to authenticated with check(user_id=auth.uid());
create policy mistakes_update on public.mistakes for update to authenticated using(user_id=auth.uid()) with check(user_id=auth.uid());

create policy certificates_select on public.certificates for select to authenticated using(user_id=auth.uid() or public.is_teacher());
create policy certificates_insert on public.certificates for insert to authenticated with check(user_id=auth.uid());
create policy certificates_update on public.certificates for update to authenticated using(user_id=auth.uid()) with check(user_id=auth.uid());

create policy weekly_read on public.weekly_leaderboard for select to authenticated using(true);

create index if not exists assignments_active_idx on public.assignments(active,created_at desc);
create index if not exists mistakes_user_idx on public.mistakes(user_id,resolved);
create index if not exists weekly_week_idx on public.weekly_leaderboard(week_start,xp desc);


-- Backfill current week's existing results so the rating is not empty after first install.
insert into public.weekly_leaderboard(user_id,week_start,display_name,class_name,attempts,best_score,total_score,xp,progress_points,updated_at)
select r.user_id,date_trunc('week',r.created_at)::date,coalesce(p.full_name,p.username),p.class_name,
       count(*)::int,max(r.score)::int,sum(r.score)::int,
       sum(round(r.score/5.0)::int + case when r.test_type='olympiad' then 10 else 0 end)::int,
       0,now()
from public.results r join public.profiles p on p.id=r.user_id
where r.created_at >= date_trunc('week',now())
group by r.user_id,date_trunc('week',r.created_at)::date,p.full_name,p.username,p.class_name
on conflict(user_id,week_start) do update set
 display_name=excluded.display_name,class_name=excluded.class_name,attempts=excluded.attempts,
 best_score=excluded.best_score,total_score=excluded.total_score,xp=excluded.xp,updated_at=now();
