create or replace function public.is_teacher()
returns boolean language sql stable security definer set search_path=public as $$
  select exists(select 1 from public.profiles where id=auth.uid() and role='teacher');
$$;

-- IMPORTANT: profiles are not editable by students. Teacher role is changed only from SQL/admin.
revoke insert, update on table public.profiles from authenticated;
grant select on table public.profiles to authenticated;

drop policy if exists profiles_insert_self on public.profiles;
drop policy if exists profiles_update_self on public.profiles;
drop policy if exists profiles_select on public.profiles;
create policy profiles_select on public.profiles for select to authenticated
using (id=auth.uid() or public.is_teacher());

create table if not exists public.assignments (
  id uuid primary key default gen_random_uuid(),
  title text not null,
  description text,
  kind text not null default 'assignment' check (kind in ('assignment','olympiad','challenge')),
  topic_ids integer[] not null default '{}',
  question_count integer not null default 15 check(question_count between 1 and 100),
  time_limit_minutes integer not null default 0,
  due_at timestamptz,
  target_class text,
  target_user_id uuid references public.profiles(id) on delete cascade,
  max_attempts integer not null default 3,
  created_by uuid not null references public.profiles(id) on delete cascade,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

alter table public.results add column if not exists assignment_id uuid references public.assignments(id) on delete set null;

create table if not exists public.mistakes (
  user_id uuid not null references public.profiles(id) on delete cascade,
  question_key text not null,
  topic_id integer not null,
  wrong_count integer not null default 0,
  correct_streak integer not null default 0,
  resolved boolean not null default false,
  updated_at timestamptz not null default now(),
  primary key(user_id,question_key)
);

create table if not exists public.certificates (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  section_id text not null,
  section_title text not null,
  score integer not null,
  code text not null unique,
  issued_at timestamptz not null default now(),
  unique(user_id,section_id)
);

create table if not exists public.weekly_leaderboard (
  user_id uuid not null references public.profiles(id) on delete cascade,
  week_start date not null,
  display_name text not null,
  class_name text,
  attempts integer not null default 0,
  best_score integer not null default 0,
  total_score integer not null default 0,
  xp integer not null default 0,
  progress_points integer not null default 0,
  updated_at timestamptz not null default now(),
  primary key(user_id,week_start)
);

alter table public.weekly_leaderboard add column if not exists progress_points integer not null default 0;

create or replace function public.update_weekly_leaderboard()
returns trigger language plpgsql security definer set search_path=public as $$
declare p public.profiles%rowtype; w date; bonus integer;
begin
  select * into p from public.profiles where id=new.user_id;
  w := date_trunc('week',new.created_at)::date;
  bonus := case when new.test_type='olympiad' then 10 else 0 end;
  insert into public.weekly_leaderboard(user_id,week_start,display_name,class_name,attempts,best_score,total_score,xp,progress_points,updated_at)
  values(new.user_id,w,coalesce(p.full_name,p.username),p.class_name,1,new.score,new.score,round(new.score/5.0)::int+bonus,0,now())
  on conflict(user_id,week_start) do update set
    display_name=excluded.display_name,
    class_name=excluded.class_name,
    attempts=public.weekly_leaderboard.attempts+1,
    best_score=greatest(public.weekly_leaderboard.best_score,excluded.best_score),
    total_score=public.weekly_leaderboard.total_score+excluded.total_score,
    xp=public.weekly_leaderboard.xp+excluded.xp,
    progress_points=public.weekly_leaderboard.progress_points+greatest(excluded.best_score-public.weekly_leaderboard.best_score,0),
    updated_at=now();
  return new;
end;$$;

drop trigger if exists results_weekly_leaderboard on public.results;
create trigger results_weekly_leaderboard after insert on public.results for each row execute procedure public.update_weekly_leaderboard();

